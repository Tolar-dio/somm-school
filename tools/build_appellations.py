"""Build the Appellations encyclopedia data from the Vitis Mundi atlas plus the academy's own full entries.

    python3 -I tools/build_appellations.py /path/to/wine-world

Writes:
  assets/js/appellations/<cc>.js   APX.<cc> = {country, regions, items}: every appellation the atlas profiles,
                                   with its atlas summary as the stub text (loaded when a country opens)
  assets/js/data/apps-index.js     APPS = {cc: {name, n, full, regions:[[id, name, n, full]]}}: small, always loaded
Full entries are written by hand in assets/js/appellations/full/<cc>/<region-slug>.js as APXF["<id>"] = {...};
this script only counts them so the lists can show which appellations have a full entry.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COUNTRIES = ["fr", "it", "es", "pt", "us"]
KEEP = ["name", "cat", "subcat", "region", "subregion", "created", "area_ha", "styles", "grapes", "summary",
        "terroir", "producers", "nerd_note", "contains", "parent", "village", "classification"]


def slug(s):
    s = s.lower()
    for a, b in (("à", "a"), ("â", "a"), ("ä", "a"), ("ç", "c"), ("é", "e"), ("è", "e"), ("ê", "e"), ("ë", "e"),
                 ("î", "i"), ("ï", "i"), ("ô", "o"), ("ö", "o"), ("ù", "u"), ("û", "u"), ("ü", "u"), ("ñ", "n")):
        s = s.replace(a, b)
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def full_ids(cc):
    ids = set()
    d = ROOT / "assets" / "js" / "appellations" / "full" / cc
    for f in sorted(d.glob("*.js")) if d.is_dir() else []:
        ids.update(re.findall(r'APXF\["([^"]+)"\]\s*=', f.read_text()))
    return ids


def main():
    ww = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "wine-world")
    out_dir = ROOT / "assets" / "js" / "appellations"
    out_dir.mkdir(parents=True, exist_ok=True)
    index = {}
    for cc in COUNTRIES:
        d = json.loads((ww / "docs" / "data" / "content" / f"{cc}.json").read_text())
        full = full_ids(cc)
        items = {}
        for pid, p in d["profiles"].items():
            it = {k: p[k] for k in KEEP if k in p and p[k] not in (None, "", [])}
            it["rslug"] = slug(p["region"])
            items[pid] = it
        order = []
        for r in d["regions"]:
            if r.get("parent_region") is None or cc == "us":
                order.append(r["name"])
        regs = {}
        for pid, it in items.items():
            regs.setdefault(it["region"], []).append(pid)
        region_rows = []
        names = sorted(regs, key=lambda n: (order.index(n) if n in order else 999, n))
        rinfo = {r["name"]: r for r in d["regions"]}
        for n in names:
            ids = sorted(regs[n], key=lambda i: items[i]["name"])
            region_rows.append({"name": n, "slug": slug(n), "tagline": rinfo.get(n, {}).get("tagline", ""),
                                "ids": ids})
        c = d["country"]
        data = {"country": {"name": c["name"], "tagline": c.get("tagline", ""),
                            "classification": c.get("classification", "")},
                "regions": region_rows, "items": items}
        js = "// Generated by tools/build_appellations.py from the Vitis Mundi atlas. Do not edit by hand.\n"
        js += f"APX.{cc} = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
        (out_dir / f"{cc}.js").write_text(js)
        index[cc] = {"name": c["name"], "n": len(items), "full": len(full & set(items)),
                     "regions": [[r["slug"], r["name"], len(r["ids"]), len(full & set(r["ids"]))] for r in region_rows]}
        print(cc, len(items), "appellations,", len(region_rows), "regions,", index[cc]["full"], "full entries")
    js = "// Generated by tools/build_appellations.py. Do not edit by hand.\nconst APPS = " + json.dumps(
        index, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "assets" / "js" / "data" / "apps-index.js").write_text(js)


if __name__ == "__main__":
    main()
