"""Build assets/js/data/atlas-index.js: place names the Vitis Mundi atlas can open, keyed by atlas hash.

    python3 -I tools/build_atlas_index.py /path/to/wine-world

Reads wine-world/docs/data/content/<cc>.json (regions, appellation profiles, sites). Lessons link the
first mention of each place to https://vitismundi.app/#<id>. Rerun after the atlas adds places.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Names that are ordinary words, grapes or styles in lesson prose; linking them would mislead.
STOP = {
    "Port", "Rosé", "Rose", "Village", "Villages", "Vin de France", "Coast", "Central", "Valley", "Bianco", "Rosso",
    "Moscato", "Malvasia", "Muscat", "Riesling", "Chardonnay", "Grenache", "Syrah", "Merlot", "Sherry",
    "Crémant", "Lambrusco", "Vermentino", "Primitivo", "Nebbiolo", "Barbera", "Dolcetto", "Sangiovese",
    "Aglianico", "Grillo", "Fiano", "Greco", "Verdicchio", "Pecorino", "Trebbiano", "Monica", "Cannonau",
    "Carignano", "Nuragus", "Girò", "Nasco", "Vernaccia", "Freisa", "Grignolino", "Ruché", "Brachetto",
    "Malvasia", "Schioppettino", "Pignolo", "Teran", "Tokaji", "Assyrtiko", "Furmint", "Pinotage", "Carmenère",
    "Vin Santo", "Retsina", "Clos", "Les Clos", "Classico", "Creation", "Northern", "Orange", "Danube",
    "Fiasco", "Escarpment", "Hermann", "Austral",
}
KEEP_REGION_NAMES = {"Madeira", "Port"}  # fine as region links even though the bare word is a style
MIN_LEN = 4


def main():
    ww = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "wine-world")
    content = ww / "docs" / "data" / "content"
    if not content.is_dir():
        raise SystemExit(f"{content} not found: pass the wine-world checkout path")
    out = {}  # cc -> [[name, id, kind], ...]
    for f in sorted(content.glob("*.json")):
        cc = f.stem
        if len(cc) != 2:
            continue
        d = json.loads(f.read_text())
        rows, seen = [], set()

        def add(name, hid, kind):
            name = (name or "").strip()
            if len(name) < MIN_LEN or name in seen:
                return
            if name in STOP and not (kind == "r" and name in KEEP_REGION_NAMES):
                return
            seen.add(name)
            rows.append([name, hid, kind])

        c = d.get("country") or {}
        if c.get("name"):
            add(c["name"], cc, "c")
        for r in d.get("regions") or []:
            add(r["name"], r["id"], "r")
            for a in r.get("alt") or []:
                add(a, r["id"], "r")
        for pid, p in (d.get("profiles") or {}).items():
            add(p.get("name"), pid, "a")
        for s in d.get("sites") or []:
            if len(s.get("name", "")) >= 6:
                add(s["name"], s["id"], "s")
        if rows:
            out[cc] = rows
    js = ("// Generated by tools/build_atlas_index.py from Tolar-dio/wine-world. Do not edit by hand.\n"
          "// ATLAS[cc] = [[name, atlas hash id, kind (c country, r region, a appellation, s site)], ...]\n"
          "const ATLAS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    dest = ROOT / "assets" / "js" / "data" / "atlas-index.js"
    dest.write_text(js)
    print(f"{sum(len(v) for v in out.values())} names in {len(out)} countries, {len(js) // 1024} KB -> {dest}")


if __name__ == "__main__":
    main()
